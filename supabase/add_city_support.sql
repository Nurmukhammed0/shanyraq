-- ============================================================
-- Поддержка нескольких городов для реестра ЖК.
-- До этой миграции город был везде захардкожен как 'Алматы'
-- (listings.city уже существовал с таким default, у zhk города
-- не было вовсе). Выполнить в Supabase -> SQL Editor.
-- ============================================================

alter table public.zhk
  add column if not exists city text not null default 'Алматы';

-- Ускоряет фильтр "только этот город" на списке/карте по мере роста таблицы.
create index if not exists zhk_city_idx on public.zhk (city);

-- listings.city уже существует (см. listings.sql) — там миграция не нужна,
-- значение 'Алматы' просто больше не хардкодится в UI при создании объявления.
